#!/usr/bin/env python3
"""Original synthetic filters; no recordings or third-party cabinet assets."""
import math,cmath,struct,hashlib,json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
rate=48000
# Frequency shaping, not microphone positions or measured speakers.
recipes=[('clean-open-2x12',65,6800,[(180,2,.65),(1800,-2,.7),(4400,-3,.7)]),
 ('chime-2x12',80,7200,[(280,-2,.8),(2400,3,.7),(4800,-5,.9)]),
 ('british-4x12',75,5700,[(140,3,.7),(800,2,.8),(3200,-4,1.1)]),
 ('tight-modern-4x12',85,6500,[(180,-2,.8),(1300,1,.8),(3900,-5,1.2)]),
 ('dark-full-4x12',55,4800,[(120,4,.65),(650,1,.8),(2700,-3,.9)])]
def coeff(kind,f,db=0,q=.707):
 w=2*math.pi*f/rate;c=math.cos(w);a=math.sin(w)/(2*q);A=10**(db/40)
 if kind=='hp': b=[(1+c)/2,-1-c,(1+c)/2];d=[1+a,-2*c,1-a]
 elif kind=='lp': b=[(1-c)/2,1-c,(1-c)/2];d=[1+a,-2*c,1-a]
 else:b=[1+a*A,-2*c,1-a*A];d=[1+a/A,-2*c,1-a/A]
 return [x/d[0] for x in b]+[d[1]/d[0],d[2]/d[0]]
entries=[];code='#include "CabinetAssets.h"\n#include <array>\nnamespace guitarrack {\nnamespace {\n'
for index,(name,hp,lp,bands) in enumerate(recipes):
 filters=[coeff('hp',hp),coeff('lp',lp)]+[coeff('peak',*b) for b in bands]
 states=[[0,0,0,0] for _ in filters];samples=[]
 for i in range(2048):
  x=1.0 if i==0 else 0.0
  for c,s in zip(filters,states):
   y=c[0]*x+c[1]*s[0]+c[2]*s[1]-c[3]*s[2]-c[4]*s[3];s[:]=[x,s[0],y,s[2]];x=y
  samples.append(x)
 response=abs(sum(x*cmath.exp(-2j*math.pi*1000*i/rate) for i,x in enumerate(samples)))
 samples=[x/response for x in samples]
 payload=struct.pack('<2048f',*samples)
 wav=b'RIFF'+struct.pack('<I',36+len(payload))+b'WAVEfmt '+struct.pack('<IHHIIHH',16,3,1,rate,rate*4,4,32)+b'data'+struct.pack('<I',len(payload))+payload
 id=hashlib.sha256(wav).hexdigest();(root/'assets/ir'/f'{name}.wav').write_bytes(wav)
 code+=f'const std::array<std::uint8_t,{len(wav)}> asset{index}{{'+','.join(str(b) for b in wav)+'};\n'
 entries.append(dict(name=name,id=id,file=f'assets/ir/{name}.wav',license='CC0-1.0',origin='Original analytic cascade generated by tools/generate_cabinet_assets.py; synthetic, not measured',sample_rate=rate,normalization='1 kHz response magnitude = 1 before float32 rounding; no runtime normalization',high_pass_hz=hp,low_pass_hz=lp,bands=bands))
code+='}\nconst std::vector<BuiltinCabinet>& builtinCabinets() {static const std::vector<BuiltinCabinet> c{'
code+=','.join('{'+json.dumps(e['id'])+','+json.dumps(e['name'])+'}' for e in entries)+'}; return c;}\n'
code+='std::vector<std::uint8_t> builtinIRBytes(const std::string& id) {if(id==syntheticIRId())return syntheticIRBytes();\n'
for i,e in enumerate(entries): code+=f'if(id=="{e["id"]}")return {{asset{i}.begin(),asset{i}.end()}};\n'
code+='return {}; }\n}\n'
(root/'src/core/CabinetAssets.cpp').write_text(code)
(root/'assets/ir/catalog.json').write_text(json.dumps({'schema_version':1,'assets':entries},indent=2)+'\n')
